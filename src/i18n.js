function translate(language, key, vars = {}) {
  const text = (STRINGS[language] || STRINGS.en)[key] ?? STRINGS.en[key];
  if (text === undefined) return key.replace(/^metric\./, '').replace(/_/g, ' ');
  return text.replace(/\{(\w+)\}/g, (_m, name) => vars[name]);
}

